#!/usr/bin/env python3
"""Render the policy's headings, paragraphs and HTTPS links for the extension."""
from html import escape
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'PRIVACY.md'
TARGET = ROOT / 'extension' / 'privacy.html'


def inline(text):
    escaped = escape(text)
    return re.sub(r'\[([^\]]+)\]\((https?://[^\s)]+)\)',
                  lambda match: '<a href="%s" rel="noopener">%s</a>' % (match[2], match[1]), escaped)


def render():
    blocks = []
    for paragraph in SOURCE.read_text(encoding='utf-8').strip().split('\n\n'):
        text = ' '.join(paragraph.splitlines())
        if text.startswith('## '):
            blocks.append('<h2>' + inline(text[3:]) + '</h2>')
        elif text.startswith('# '):
            blocks.append('<h1>' + inline(text[2:]) + '</h1>')
        else:
            blocks.append('<p>' + inline(text) + '</p>')
    return '''<!doctype html>
<!-- Generated by bin/render-privacy.py from PRIVACY.md. Do not edit directly. -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>roku-sync privacy policy</title>
<style>body{max-width:760px;margin:32px auto;padding:0 20px;font:16px/1.6 system-ui;color:#172033;background:#fff}a{color:#204db8}h1,h2{line-height:1.3}h2{font-size:21px;margin-top:28px}</style>
</head>
<body>
''' + '\n'.join(blocks) + '\n</body>\n</html>\n'


if __name__ == '__main__':
    content = render()
    if '--check' in sys.argv:
        if not TARGET.exists() or TARGET.read_text(encoding='utf-8') != content:
            sys.exit('Run python3 bin/render-privacy.py to update the bundled policy.')
    else:
        TARGET.write_text(content, encoding='utf-8')
